"""Independent fixed-case initial-flop qualification and offline review check; no optimizer."""
import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
HELPER = ROOT / 'scripts/check-supplied-flop-action-bounds.py'
spec = importlib.util.spec_from_file_location('flop_feedback_bounds', HELPER)
bounds = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = bounds
spec.loader.exec_module(bounds)
physical = bounds.physical
read, require, close = bounds.read, bounds.require, bounds.close
CONNECTED = ROOT / 'docs/data/supplied-four-button-hand-connected-flop-request.json'
BOUNDS = ROOT / 'docs/data/supplied-four-button-hand-flop-action-bounds.json.gz'
BOUNDS_SHA = 'b55df9ff934aaf9dc09659268c0b8909f81914d7dc8bb9e58e3b535bbe3ea013'
# Java's canonical object hash is separately regenerated by complete owned physical replay.
REPORT_HASH = '49b1be1e91bb0ae7cae6a3171f4e15e516fc0a52be80efabc6d281e8ec5863d8'
REPORT_BYTES_SHA = 'b3b89e76c4747fc8c1b27a0a84bb34cac587c7377f7525c934f75254824221ff'
STATUS = 'INITIAL_PHYSICAL_FLOP_INTERVAL_FEEDBACK_RESEARCH_ONLY'
DRILL_STATUS = 'INITIAL_PHYSICAL_FLOP_DRILL_RESEARCH_ONLY'
EV_SCOPE = 'ABSOLUTE_TERMINAL_PROFIT_OPTIMAL_FUTURE_CONTINUATION_BB/v1'
REACH_UNITS = 'COUNTERFACTUAL_QUESTION_GIVEN_PHYSICAL_FLOP_HERO_PAST_CANCELLED/v1'


def classification(lower, upper, limit):
    require(all(math.isfinite(x) for x in (lower, upper, limit))
            and 0 <= lower <= upper and 0 < limit <= .01, 'Invalid loss interval')
    return 'WITHIN_LIMIT' if upper <= limit else 'OUTSIDE_LIMIT' if lower > limit else 'STRATEGY_DEPENDENT'


def check_policy(actual, policy, solution_hash, local, root, roots, prior, decision):
    require(set(actual) == {'iterations', 'solutionHash', 'fullParentQuality', 'reachedFlopQuality',
            'actualQuestionRootReach', 'actualQuestionReachGivenPhysicalFlop',
            'counterfactualQuestionReachGivenPhysicalFlop', 'globalHeroBestResponseBb', 'globalHeroUpperBb',
            'inclusionMarginBb', 'insideDeclaredFace', 'boundsChecked', 'maximumBoundViolationBb',
            'actionUtilitiesBb', 'actionLossBb', 'decisionRegretBb', 'failures'}, 'Unsupported policy check fields')
    require(actual['iterations'] == policy['iterations'] and actual['solutionHash'] == solution_hash,
            'Reference identity differs')
    strategy = policy['strategy']
    physical.compare_quality(actual['fullParentQuality'], physical.quality(root, strategy))
    require(actual['reachedFlopQuality'] == local, 'Reached-flop evidence differs')
    weights = [(i, w['conditionalProbability'] * physical.P * strategy[
        f'5:supplied-connected-single-flop:supplied-conditional-preflop:{w["dealtCombos"][5]}:']['call'])
        for i, w in enumerate(prior)]
    selected = {i for i, _, _ in roots}
    actual_reach = math.fsum(p for i, p in weights if i in selected)
    close(actual['actualQuestionRootReach'], actual_reach, 'Actual raw question reach differs', mass=True)
    close(actual['actualQuestionReachGivenPhysicalFlop'], actual_reach / physical.P,
          'Actual conditional question reach differs', mass=True)
    # At this owned boundary BB's call is its own past and cancels. There are no opponent past actions.
    cf_reach = math.fsum(p for _, p, _ in roots)
    close(actual['counterfactualQuestionReachGivenPhysicalFlop'], cf_reach, 'Hero past was not cancelled', mass=True)
    values = {}
    for action in decision['actions']:
        forced = physical.Node(-1, edges=tuple((p / cf_reach, dict(n.edges)[action['action']])
                                               for _, p, n in roots))
        values[action['action']] = physical.best_response(forced, strategy, 5)
    losses = {a: max(values.values()) - v for a, v in values.items()}
    require(set(actual['actionUtilitiesBb']) == set(values) and set(actual['actionLossBb']) == set(losses),
            'Reference action inventory differs')
    for a in values:
        close(actual['actionUtilitiesBb'][a], values[a], 'Forced-action continuation value differs')
        close(actual['actionLossBb'][a], losses[a], 'Reference action loss differs')
    br = physical.best_response(root, strategy, 5)
    upper = decision['actions'][0]['diagnostic']['globalHeroUpperValue']
    margin = upper + bounds.EPS - br
    close(actual['globalHeroBestResponseBb'], br, 'Whole-parent hero response differs')
    close(actual['globalHeroUpperBb'], upper, 'Whole-parent face upper differs')
    close(actual['inclusionMarginBb'], margin, 'Face inclusion margin differs')
    included = margin >= -bounds.EPS
    require(actual['insideDeclaredFace'] is included and actual['boundsChecked'] is included,
            'Reference face/check status differs')
    failures = []
    if not included:
        failures.append('REFERENCE_OUTSIDE_DECLARED_FACE')
        require(actual['maximumBoundViolationBb'] is None, 'Outside-face reference cannot claim checked bounds')
    else:
        violations = [0]
        for a in decision['actions']:
            v, loss = values[a['action']], losses[a['action']]
            violations += [a['lowerUtilityBb'] - v, v - a['upperUtilityBb'],
                           a['lowerLossBb'] - loss, loss - a['upperLossBb']]
        worst = max(violations)
        close(actual['maximumBoundViolationBb'], worst, 'Reference bound violation differs')
        if worst > bounds.EPS:
            failures.append('REFERENCE_OUTSIDE_DECISION_BOUNDS')
    if actual['fullParentQuality']['nashConvBb'] > .001:
        failures.append('FULL_PARENT_GAP')
    if local['conditionalBestResponse'] is None or local['conditionalBestResponse']['nashConvBb'] > .001:
        failures.append('REACHED_FLOP_GAP')
    if actual_reach / physical.P < .0001:
        failures.append('INSUFFICIENT_ACTUAL_QUESTION_REACH')
    if cf_reach < .0001:
        failures.append('INSUFFICIENT_COUNTERFACTUAL_QUESTION_REACH')
    regret = math.fsum(strategy[decision['informationSet']][a] * loss for a, loss in losses.items())
    close(actual['decisionRegretBb'], regret, 'Selected decision regret differs')
    if regret > .01:
        failures.append('SELECTED_DECISION_REGRET')
    require(actual['failures'] == failures, 'Reference rejection reasons differ')
    return failures


def check(request_path, report_path, drill_path):
    request, request_bytes, _ = read(request_path)
    report, report_bytes, expanded = read(report_path)
    drill, drill_bytes, _ = read(drill_path)
    pinned, pinned_bytes, _ = read(BOUNDS)
    require(hashlib.sha256(pinned_bytes).hexdigest() == BOUNDS_SHA and report['bounds'] == pinned,
            'Complete physical bounds lineage differs')
    endpoint_receipt = bounds.check(CONNECTED, BOUNDS)
    _, context = physical.check(CONNECTED, bounds.PARENT, include_context=True)
    parent = pinned['parent']
    declared = dict(request)
    declared['connected'] = dict(request['connected'], input=physical.canonical_input(request['connected']['input']))
    require(set(request) == {'schemaVersion', 'connected', 'hero', 'informationSet', 'maximumLossBb'}
            and request['schemaVersion'] == 'pokerlab-supplied-flop-feedback-request/v1'
            and declared['connected'] == parent['request'] and request['hero'] == 5
            and request['informationSet'] == '5:supplied-flop-one-bet:7d 7h:|BB:call:2s 8s Ts:'
            and request['maximumLossBb'] == .01, 'Unsupported fixed-case feedback request')
    require(set(report) == {'schemaVersion', 'publicationStatus', 'trainerAdmission', 'request', 'evScope', 'reachUnits',
                           'bounds', 'context', 'moves', 'primary', 'references', 'qualifiedForOfflineDrill', 'rejectionReasons'}
            and report['schemaVersion'] == 'pokerlab-supplied-flop-feedback-report/v1'
            and report['publicationStatus'] == STATUS and report['trainerAdmission'] is False
            and report['request'] == declared and report['evScope'] == EV_SCOPE
            and report['reachUnits'] == REACH_UNITS, 'Feedback identity differs')
    handoff = parent['handoffs'][0]
    seats = ['UTG', 'HJ', 'CO', 'BTN', 'SB', 'BB']
    players = [dict(seat=s, status='FOLDED' if handoff['folded'][i] else 'ACTING' if i == 5
                    else 'ALL_IN' if handoff['remainingStackBb'][i] == 0 else 'ACTIVE',
                    committedBb=handoff['committedBb'][i], remainingStackBb=handoff['remainingStackBb'][i])
               for i, s in enumerate(seats)]
    table = dict(hero='BB', heroCards='7d 7h', board=handoff['flop'], publicHistory=handoff['publicHistory'],
                 preflopHistory=handoff['completePreflopHistory'], potBb=math.fsum(handoff['committedBb']),
                 toCallBb=0, betSizeBb=min(handoff['remainingStackBb'][3], handoff['remainingStackBb'][5],
                 math.floor(math.fsum(handoff['committedBb']) * .5 * 1e6 + .5) / 1e6),
                 players=players, legalActions=['check', 'bet'])
    require(report['context'] == table, 'Owned physical table context differs')
    decision = next(d for d in pinned['decisions'] if d['informationSet'] == request['informationSet'])
    moves = [dict(action=a['action'], lowerEvBb=a['lowerUtilityBb'], upperEvBb=a['upperUtilityBb'],
                  lowerLossBb=a['lowerLossBb'], upperLossBb=a['upperLossBb'],
                  classification=classification(a['lowerLossBb'], a['upperLossBb'], request['maximumLossBb']))
             for a in decision['actions']]
    require(report['moves'] == moves, 'Conservative interval classification differs')
    roots = [(i, w['conditionalProbability'], context['selected'][i, '|BB:call'])
             for i, w in enumerate(context['prior'])
             if context['selected'][i, '|BB:call'].key == request['informationSet']]
    failures = []
    classes = {m['classification'] for m in moves}
    if 'WITHIN_LIMIT' not in classes:
        failures.append('NO_ROBUST_MOVE_WITHIN_LIMIT')
    if 'OUTSIDE_LIMIT' not in classes:
        failures.append('NO_ROBUST_MOVE_OUTSIDE_LIMIT')
    primary_failures = check_policy(report['primary'], parent['candidate'], parent['solutionHash'],
                                   parent['reachedFlopQuality'][0], context['root'], roots, context['prior'], decision)
    failures += ['PRIMARY:' + f for f in primary_failures]
    require([r['iterations'] for r in report['references']] == [2000, 4000], 'Fresh reference coverage differs')
    for actual, reference in zip(report['references'], pinned['freshReferences'], strict=True):
        ref_failures = check_policy(actual, reference['policy'], reference['solutionHash'], reference['reachedFlopQuality'],
                                    context['root'], roots, context['prior'], decision)
        failures += [str(actual['iterations']) + ':' + f for f in ref_failures]
    require(report['rejectionReasons'] == sorted(set(failures))
            and report['qualifiedForOfflineDrill'] is (not failures), 'Qualification rejection reasons differ')
    require(hashlib.sha256(report_bytes).hexdigest() == REPORT_BYTES_SHA,
            'Fixed-case Java canonical report hash byte binding differs')
    question = dict(reportHash=REPORT_HASH, publicationStatus=DRILL_STATUS, trainerAdmission=False,
                    selection='SINGLE_QUALIFIED_INITIAL_FLOP_QUESTION/v1', informationSet=request['informationSet'],
                    context=table, maximumLossBb=.01, securitySlackBb=1e-8, minimumReach=.0001,
                    reachUnits=REACH_UNITS, evScope=EV_SCOPE)
    require(set(drill) == {'schemaVersion', 'question', 'attempts', 'counts'}
            and drill['schemaVersion'] == 'pokerlab-supplied-flop-drill/v1'
            and drill['question'] == question and len(drill['attempts']) <= 100,
            'Owned drill question differs')
    counts = dict(withinLimit=0, outsideLimit=0, strategyDependent=0)
    names = dict(WITHIN_LIMIT='withinLimit', OUTSIDE_LIMIT='outsideLimit', STRATEGY_DEPENDENT='strategyDependent')
    for i, attempt in enumerate(drill['attempts']):
        selected = next((m for m in moves if m['action'] == attempt['action']), None)
        require(selected is not None, 'Illegal drill action')
        expected = dict(index=i, action=selected['action'], feedback=dict(reportHash=REPORT_HASH,
                        publicationStatus=DRILL_STATUS, trainerAdmission=False, evScope=EV_SCOPE,
                        maximumLossBb=.01, selected=selected, alternatives=moves))
        require(attempt == expected, 'Saved drill feedback differs')
        counts[names[selected['classification']]] += 1
    require(drill['counts'] == counts, 'Attempt counts differ')
    return dict(schemaVersion='pokerlab-independent-flop-feedback/v1', trainerAdmission=False,
                fixedCaseOnly=True, freshLpSolves=0, originalEndpointCertificatesChecked=endpoint_receipt['originalEndpointCertificatesChecked'],
                fullParentSecurityChecked=True, physicalQuestionContextChecked=True,
                primaryAndFreshPoliciesChecked=3, optimalContinuationActionValuesChecked=6,
                actualAndCounterfactualReachChecked=True, attemptsChecked=len(drill['attempts']),
                javaCanonicalReportHashPin=REPORT_HASH, checkerSourceSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                boundsHelperSourceSha256=hashlib.sha256(HELPER.read_bytes()).hexdigest(),
                physicalHelperSourceSha256=hashlib.sha256(bounds.HELPER.read_bytes()).hexdigest(),
                requestStoredBytesSha256=hashlib.sha256(request_bytes).hexdigest(),
                reportStoredBytesSha256=hashlib.sha256(report_bytes).hexdigest(),
                reportExpandedBytesSha256=hashlib.sha256(expanded).hexdigest(),
                drillStoredBytesSha256=hashlib.sha256(drill_bytes).hexdigest(), pinnedBoundsStoredBytesSha256=BOUNDS_SHA)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('request', type=Path)
    p.add_argument('report', type=Path)
    p.add_argument('drill', type=Path)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    require(not args.output.exists(), 'Receipt output must be new')
    require(args.output.resolve() not in {args.request.resolve(), args.report.resolve(), args.drill.resolve()}, 'Paths must differ')
    receipt = check(args.request, args.report, args.drill)
    with args.output.open('x', encoding='utf-8') as stream:
        json.dump(receipt, stream, indent=2)
        stream.write('\n')
    print(json.dumps(receipt))


if __name__ == '__main__':
    main()
